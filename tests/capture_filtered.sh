#!/bin/sh
# Capture regression checksums of libbink2's own filtered output.
# These pin behaviour; they are not a correctness reference.
set -eu

ROOT=$(cd "$(dirname "$0")/.." && pwd)
MEDIA=${BINK2_TEST_MEDIA:-}
DUMP=${BINK2_DUMP:-$ROOT/build/bink2_dump}
OUT=${BINK2_FILTERED_OUT:-$ROOT/build/filtered}

if [ -z "$MEDIA" ]; then
    echo "BINK2_TEST_MEDIA is not set" >&2
    exit 1
fi
if [ ! -x "$DUMP" ]; then
    echo "$DUMP not found; build with -DBINK2_BUILD_TOOLS=ON" >&2
    exit 1
fi

mkdir -p "$OUT"
"$DUMP" --frames 236 --yuv "$OUT/sc13.yuv" \
    "$MEDIA/sc13_01_partial.bk2" >/dev/null
"$DUMP" --frames 490 --yuv "$OUT/ge.yuv" \
    "$MEDIA/ge_video_86l.bk2" >/dev/null
"$DUMP" --frames 32 --yuv "$OUT/kb2j.yuv" \
    "$ROOT/tests/media/synthetic_kb2j.bk2" >/dev/null

{
    echo '#ifndef LIBBINK2_FILTERED_CHECKSUMS_H'
    echo '#define LIBBINK2_FILTERED_CHECKSUMS_H'
    echo
    echo '/* libbink2'"'"'s own filtered output; pins behaviour, not a'
    echo ' * correctness reference. Generated by tests/capture_filtered.sh. */'
    echo
    echo '#include "reference_checksums.h"'
    echo
    echo '/* KB2f, 1280x736, frames 0..235 of the partial sample. */'
    echo 'static const Bink2FrameChecksum bink2_kb2f_filtered_checksums[] = {'
    python3 "$ROOT/tests/checksum_frames.py" --kind video \
        --input "$OUT/sc13.yuv" --width 1280 --height 736 --frames 236
    echo '};'
    echo
    echo '/* KB2g, 1024x576, 490 frames. */'
    echo 'static const Bink2FrameChecksum bink2_kb2g_filtered_checksums[] = {'
    python3 "$ROOT/tests/checksum_frames.py" --kind video \
        --input "$OUT/ge.yuv" --width 1024 --height 576 --frames 490
    echo '};'
    echo
    echo '/* Synthetic KB2j, 160x120, 32 frames. */'
    echo 'static const Bink2FrameChecksum bink2_kb2j_filtered_checksums[] = {'
    python3 "$ROOT/tests/checksum_frames.py" --kind video \
        --input "$OUT/kb2j.yuv" --width 160 --height 120 --frames 32
    echo '};'
    echo
    echo '#endif'
} > "$ROOT/tests/filtered_checksums.h"

echo "wrote $ROOT/tests/filtered_checksums.h"
